class SchemaError(Exception):
    pass


# ---------------------------------------------------------------------------------------------------------------------
# Loading the schemas into a small model: definitions that are structs, string enums, unions told apart by a field, or
# free JSON; fields with a type made of primitives, arrays, maps and references.


@dataclass
class TypeRef:
    kind: str  # string | int | int64 | number | bool | time | any | array | map | ref
    of: "TypeRef | None" = None
    ref: str = ""


@dataclass
class Field:
    name: str
    type: TypeRef
    required: bool
    doc: str = ""
    pointer: bool = False  # x-go-pointer: a Go scalar whose absence means something
    literal: object = None  # const fields retain literal types in TypeScript


@dataclass
class Def:
    name: str
    kind: str  # struct | enum | union | any
    doc: str = ""
    fields: list[Field] = field(default_factory=list)
    values: list[str] = field(default_factory=list)  # enum
    variants: list[str] = field(default_factory=list)  # union: the variants' defs
    discriminator: str = ""
    tag: str = ""  # a union variant's discriminator value
    since: int = 0  # x-since of a union variant
    union: str = ""  # the union a variant belongs to
    extra: bool = False  # explicit additionalProperties: retain extra keys as opaque JSON
    side: str = ""  # the file's x-side: "plugin" is generated into the SDKs only
    exclusive: list[str] = field(default_factory=list)  # object oneOf: exactly one required payload
    json_types: list[TypeRef] = field(default_factory=list)  # bounded untagged JSON, typed in TS
    preserve_required: bool = False  # strict stream fields/serialization; legacy native models stay permissive
    unknown_policy: str = "skip"  # stream operations recover; lifecycle requests reject


def is_scalar(s: dict) -> bool:
    return s.get("type") in ("string", "integer", "number", "boolean") and "enum" not in s


def load() -> dict[str, Def]:
    raw: dict[str, tuple[str, dict]] = {}
    sides: dict[str, str] = {}
    for f in SCHEMA_FILES:
        doc = json.loads((SCHEMA_DIR / f).read_text())
        sides[f] = doc.get("x-side", "")
        if sides[f] and sides[f] not in SIDES:
            raise SchemaError(f"{f}: x-side {sides[f]!r}: only {', '.join(SIDES)}")
        for name, s in doc.get("$defs", {}).items():
            if name in raw:
                raise SchemaError(f"{f}: $defs/{name} is also in {raw[name][0]}: definition names are global")
            raw[name] = (f, s)

    def resolve(ref: str, here: str) -> str:
        m = re.fullmatch(r"(?:([a-z.]+\.json))?#/\$defs/([A-Za-z0-9]+)", ref)
        if not m:
            raise SchemaError(f"{here}: $ref {ref!r}: only #/$defs/X and <file>.json#/$defs/X")
        f, name = m.group(1) or raw.get(here, (None,))[0], m.group(2)
        if name not in raw:
            raise SchemaError(f"$ref {ref!r}: no definition {name}")
        if m.group(1) and raw[name][0] != m.group(1):
            raise SchemaError(f"$ref {ref!r}: {name} is in {raw[name][0]}")
        return name

    def typeof(s: dict, at: str, aliases: tuple[str, ...] = ()) -> TypeRef:
        if "$ref" in s:
            name = resolve(s["$ref"], at.split(".")[0])
            target = raw[name][1]
            if "$ref" in target:
                if name in aliases:
                    raise SchemaError(f"{at}: cyclic validation alias {name}")
                return typeof(target, name, aliases + (name,))
            if target.get("x-untagged"):
                return TypeRef("ref", ref=name) if target.get("x-json-value") else TypeRef("any")
            if is_scalar(target):
                return typeof(target, name)
            return TypeRef("ref", ref=name)
        t = s.get("type")
        if t is None:
            if "const" in s:
                return TypeRef("string")
            return TypeRef("any")
        if t == "null":
            return TypeRef("null")
        if t == "string":
            return TypeRef("time") if s.get("format") == "date-time" else TypeRef("string")
        if t == "integer":
            return TypeRef("int64") if s.get("x-go-type") == "int64" else TypeRef("int")
        if t == "number":
            return TypeRef("number")
        if t == "boolean":
            return TypeRef("bool")
        if t == "array":
            return TypeRef("array", of=typeof(s.get("items", {}), at))
        if t == "object":
            if s.get("properties"):
                raise SchemaError(f"{at}: an inline object with properties: make it a definition")
            ap = s.get("additionalProperties", {})
            return TypeRef("map", of=typeof(ap if isinstance(ap, dict) else {}, at))
        raise SchemaError(f"{at}: type {t!r} is not in the subset")

    defs: dict[str, Def] = {}
    for name, (f, s) in raw.items():
        doc = s.get("description", "")
        if is_scalar(s):
            continue  # a named string (an id, a host): used as its type where it is referenced
        if "$ref" in s:
            typeof(s, name)  # validation-only alias: reuse the referenced native wire type, checking cycles
            continue
        if s.get("x-untagged"):
            if s.get("x-json-value"):
                defs[name] = Def(name, "any", doc, json_types=[typeof(v, name) for v in s["oneOf"]])
            else:
                defs[name] = Def(name, "any", doc)
        elif "oneOf" in s and s.get("type") != "object":
            disc = s.get("x-discriminator")
            if not disc:
                raise SchemaError(f"{name}: a oneOf needs x-discriminator (or x-untagged for free JSON)")
            variants = [resolve(v["$ref"], name) for v in s["oneOf"]]
            defs[name] = Def(name, "union", doc, variants=variants, discriminator=disc)
        elif s.get("type") == "string" and "enum" in s:
            defs[name] = Def(name, "enum", doc, values=list(s["enum"]))
        elif s.get("type") == "object":
            fields = []
            req = set(s.get("required", []))
            for fname, fs in s.get("properties", {}).items():
                fields.append(Field(fname, typeof(fs, f"{name}.{fname}"), fname in req, fs.get("description", ""),
                                    bool(fs.get("x-go-pointer")), fs.get("const")))
            exclusive = []
            for option in s.get("oneOf", []):
                if set(option) != {"required"} or len(option["required"]) != 1:
                    raise SchemaError(f"{name}: object oneOf supports only single required payload fields")
                payload = option["required"][0]
                if payload not in s.get("properties", {}) or payload in req or payload in exclusive:
                    raise SchemaError(f"{name}: object oneOf payload must be distinct, declared and optional")
                exclusive.append(payload)
            extra = s.get("additionalProperties")
            keep_extra = extra is True or isinstance(extra, dict)
            if keep_extra and any(go_field(f.name) == "AdditionalProperties" or lower_camel(f.name) == "additionalProperties"
                                  for f in fields):
                raise SchemaError(f"{name}: additionalProperties is reserved for the extra-key map")
            defs[name] = Def(name, "struct", doc, fields=fields, since=s.get("x-since", 0), extra=keep_extra,
                             exclusive=exclusive)
        else:
            raise SchemaError(f"{name}: not a struct, string enum, discriminated union or x-untagged")
        defs[name].side = sides[f]
        defs[name].preserve_required = bool(s.get("x-preserve-required"))
        defs[name].unknown_policy = s.get("x-unknown-policy", "skip")
        if defs[name].unknown_policy not in ("skip", "recover", "reject"):
            raise SchemaError(f"{name}: unsupported x-unknown-policy")

    for u in [d for d in defs.values() if d.kind == "union"]:
        for v in u.variants:
            vd = defs[v]
            if vd.kind != "struct":
                raise SchemaError(f"{u.name}: variant {v} is not an object")
            tagf = next((x for x in vd.fields if x.name == u.discriminator), None)
            const = raw[v][1]["properties"].get(u.discriminator, {}).get("const")
            if tagf is None or not tagf.required or not isinstance(const, str):
                raise SchemaError(f"{v}: the discriminator {u.discriminator} is required and a const string")
            if vd.union:
                raise SchemaError(f"{v}: in two unions")
            vd.tag, vd.union = const, u.name
            vd.preserve_required = vd.preserve_required or u.preserve_required
            vd.fields = [x for x in vd.fields if x.name != u.discriminator]
        tags = [defs[v].tag for v in u.variants]
        if len(set(tags)) != len(tags):
            raise SchemaError(f"{u.name}: two variants with the same {u.discriminator}")
    return defs


@dataclass
class Call:
    name: str  # as on the wire: connector.status, event.kb.changed
    sender: str  # hub | program
    params: str  # the definition its params hold to
    result: str = ""  # a call's answer's definition; "" any JSON (and always for an event)
    event: bool = False


def load_calls(defs: dict[str, Def]) -> list[Call]:
    """The calls and events of the schema files' x-methods / x-events: what the generated tables say each one holds."""
    calls: dict[str, Call] = {}
    for f in SCHEMA_FILES:
        doc = json.loads((SCHEMA_DIR / f).read_text())
        for key, event in (("x-methods", False), ("x-events", True)):
            for name, spec in doc.get(key, {}).items():
                if name in calls:
                    raise SchemaError(f"{f}: {key} {name} is described twice")
                unknown = set(spec) - {"from", "params", "result", "description"}
                if unknown or spec.get("from") not in ("hub", "program") or (event and "result" in spec):
                    raise SchemaError(f"{f}: {key} {name}: from (hub | program), params, result (calls only), description")
                for ref in (spec.get("params"), spec.get("result")):
                    if ref is not None and (ref not in defs or defs[ref].kind not in ("struct", "any")):
                        raise SchemaError(f"{f}: {key} {name}: {ref!r} is not an object definition")
                calls[name] = Call(name, spec["from"], spec["params"], spec.get("result", ""), event)
    return list(calls.values())


def go_calls(calls: list[Call]) -> list[str]:
    if not calls:
        return []
    out = ["// Call is one call or event of an extension point's protocol (the schemas' x-methods and x-events): who",
           "// sends it (hub or program), and the definitions its params and its answer hold to (Result \"\" is any",
           "// JSON; an event has no answer).",
           "type Call struct {", "\tName, From, Params, Result string", "\tEvent                      bool", "}", "",
           "// Calls are the calls and events the schemas describe, by name as on the wire.",
           "var Calls = map[string]Call{"]
    for c in calls:
        ev = ", Event: true" if c.event else ""
        out.append(f"\t{json.dumps(c.name)}: {{Name: {json.dumps(c.name)}, From: {json.dumps(c.sender)}, "
                   f"Params: {json.dumps(c.params)}, Result: {json.dumps(c.result)}{ev}}},")
    return out + ["}", ""]


def ts_calls(calls: list[Call]) -> list[str]:
    if not calls:
        return []
    out = ["/** One call or event of an extension point's protocol: who sends it, and the definitions its params and",
           " * its answer hold to (no result: any JSON; an event has no answer). */",
           "export interface Call {", '  from: "hub" | "program";', "  params: string;", "  result?: string;",
           "  event?: boolean;", "}", "", "/** The calls and events the schemas describe, by name as on the wire. */",
           "export const CALLS: Record<string, Call> = {"]
    for c in calls:
        parts = [f"from: {json.dumps(c.sender)}", f"params: {json.dumps(c.params)}"]
        if c.result:
            parts.append(f"result: {json.dumps(c.result)}")
        if c.event:
            parts.append("event: true")
        out.append(f"  {json.dumps(c.name)}: {{ {', '.join(parts)} }},")
    return out + ["};", ""]


def flat_fields(defs: dict[str, Def], u: Def) -> list[Field]:
    """A union's variants' fields, once each, in order of first appearance: what Go's flat struct holds."""
    out: dict[str, Field] = {}
    for v in u.variants:
        for f in defs[v].fields:
            if f.name in out:
                if not same_type(flat(defs, out[f.name].type), flat(defs, f.type)) or out[f.name].pointer != f.pointer:
                    raise SchemaError(f"{u.name}: field {f.name} has different types in its variants")
                continue
            out[f.name] = f
    return list(out.values())


def flat(defs: dict[str, Def], t: TypeRef) -> TypeRef:
    """t as Go's flat struct holds it: an enum is a string."""
    return TypeRef("string") if t.kind == "ref" and defs[t.ref].kind == "enum" else t


def same_type(a: TypeRef, b: TypeRef) -> bool:
    if a.kind != b.kind or a.ref != b.ref:
        return False
    return a.of is None and b.of is None or (a.of is not None and b.of is not None and same_type(a.of, b.of))


# ---------------------------------------------------------------------------------------------------------------------
# Names.

INITIALISMS = {"id": "ID", "url": "URL", "api": "API", "http": "HTTP", "rpc": "RPC", "ui": "UI", "tz": "TZ",
               "os": "OS", "cli": "CLI", "json": "JSON"}


def camel(s: str) -> str:
    return "".join(INITIALISMS.get(p, p[:1].upper() + p[1:]) for p in re.split(r"[_.\-]", s) if p)


def go_field(s: str) -> str:
    return "".join(INITIALISMS.get(p, p[:1].upper() + p[1:]) for p in s.split("_"))


def lower_camel(s: str) -> str:
    parts = re.split(r"[_.\-]", s)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def plural(s: str) -> str:
    if s.endswith("y") and not s.endswith("ey"):
        return s[:-1] + "ies"
    if s.endswith("s"):
        return s + "es"
    return s + "s"


def upper_snake(s: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return re.sub(r"[^A-Za-z0-9]+", "_", s).upper()


def named(name: str, doc: str) -> str:
    """A Go doc comment starting with the name: "View: a view…"."""
    if not doc:
        return ""
    if len(doc) > 1 and doc[0].isupper() and doc[1].islower():
        doc = doc[0].lower() + doc[1:]
    return f"{name}: {doc}"


def comment(prefix: str, text: str, width: int = 118) -> list[str]:
    if not text:
        return []
    words, lines, cur = text.split(), [], ""
    for w in words:
        if cur and len(prefix) + len(cur) + 1 + len(w) > width:
            lines.append(prefix + cur)
            cur = w
        else:
            cur = f"{cur} {w}" if cur else w
    if cur:
        lines.append(prefix + cur)
    return lines


def unknown_doc(d: Def) -> str:
    prefix = f"A {d.discriminator} this app does not know, or a variant it could not read: "
    return prefix + {"skip": "skipped when drawn.", "recover": "reject the batch and request a full snapshot.",
                     "reject": "reject the entire request."}[d.unknown_policy]


def reserved_keys(defs: dict[str, Def], d: Def) -> list[str]:
    keys = [f.name for f in d.fields]
    if d.union:
        keys.append(defs[d.union].discriminator)
    return keys


# ---------------------------------------------------------------------------------------------------------------------
# Go: one package, no dependencies. A union is one flat struct (its variants' fields, all optional) with the
# discriminator: what the hub has always decoded views into.


def gen_go(defs: dict[str, Def], calls: list[Call] | None = None) -> str:
    uses_time = any(f.type.kind == "time" for d in defs.values() for f in d.fields)
    out = ["// Code generated by scripts/gen/extension_schema.py from schema/extension/. DO NOT EDIT.", "",
           "// Package wire holds the extension protocol's and views' types (schema/extension/).",
           "package wire", "", "import (", '\t"encoding/json"']
    if uses_time:
        out.append('\t"time"')
    out += [")", ""]

    def gtype(t: TypeRef, optional: bool, pointer: bool) -> str:
        k = t.kind
        if k == "string":
            return "*string" if pointer else "string"
        if k == "int":
            return "*int" if pointer else "int"
        if k == "int64":
            return "*int64" if pointer else "int64"
        if k == "number":
            return "*float64" if pointer else "float64"
        if k == "bool":
            return "*bool" if pointer else "bool"
        if k == "time":
            return "time.Time"
        if k == "any":
            return "json.RawMessage"
        if k == "array":
            return "[]" + gtype(t.of, False, False)
        if k == "map":
            return "map[string]" + gtype(t.of, False, False)
        d = defs[t.ref]
        if d.kind == "enum":
            return "string"
        return ("*" if optional else "") + t.ref

    def field_line(f: Field, force_optional: bool = False) -> list[str]:
        optional = force_optional or not f.required
        typ = gtype(f.type, optional, f.pointer)
        tag = f.name
        if optional:
            # x-go-pointer on a list: an empty one means something (replaces), only a nil one is left out.
            tag += ",omitzero" if f.type.kind == "time" or f.type.kind == "array" and f.pointer else ",omitempty"
        return comment("\t// ", f.doc) + [f"\t{go_field(f.name)} {typ} `json:\"{tag}\"`"]

    # Preserve required native union fields only when reached from an explicitly preserving stream object.
    # Ancestor wrappers override native children, never the legacy public models' encoders.
    def refs(t: TypeRef) -> list[str]:
        if t.kind == "ref":
            return [t.ref]
        return refs(t.of) if t.of else []

    reachable: set[str] = set()

    def visit(name: str) -> None:
        if name in reachable:
            return
        reachable.add(name)
        d = defs[name]
        for f in flat_fields(defs, d) if d.kind == "union" else d.fields:
            for ref in refs(f.type):
                visit(ref)

    for d in defs.values():
        if d.preserve_required:
            visit(d.name)
    wrapped = {name for name in reachable if defs[name].kind == "union" and not defs[name].preserve_required}
    while True:
        ancestors = {name for name in reachable if not defs[name].preserve_required
                     and any(ref in wrapped for f in defs[name].fields for ref in refs(f.type))}
        if ancestors <= wrapped:
            break
        wrapped |= ancestors

    def wire_type(t: TypeRef, optional: bool, pointer: bool) -> str:
        if t.kind == "ref" and t.ref in wrapped:
            return ("*" if optional else "") + "requiredJSON" + t.ref
        if t.kind == "array":
            return "[]" + wire_type(t.of, False, False)
        if t.kind == "map":
            return "map[string]" + wire_type(t.of, False, False)
        return gtype(t, optional, pointer)

    def converted(t: TypeRef, value: str, optional: bool, pointer: bool) -> str:
        typ = wire_type(t, optional, pointer)
        if typ == gtype(t, optional, pointer):
            return value
        if t.kind == "ref":
            return f"({typ})({value})"
        if t.kind == "array":
            body = f"for i, item := range {value} {{ out[i] = {converted(t.of, 'item', False, False)} }}"
            allocation = f"make({typ}, len({value}))"
        else:
            body = f"for key, item := range {value} {{ out[key] = {converted(t.of, 'item', False, False)} }}"
            allocation = f"make({typ}, len({value}))"
        return f"func() {typ} {{ if {value} == nil {{ return nil }}; out := {allocation}; {body}; return out }}()"

    def marshaler(d: Def, name: str) -> list[str]:
        fields = flat_fields(defs, d) if d.kind == "union" else d.fields
        groups: dict[tuple[str, ...], list[str]] = {}
        if d.kind == "union":
            for variant in d.variants:
                required = tuple(sorted(f.name for f in defs[variant].fields if f.required))
                groups.setdefault(required, []).append(defs[variant].tag)
        else:
            groups[tuple(f.name for f in fields if f.required)] = []
        lines = [f"func (v {name}) MarshalJSON() ([]byte, error) {{",
                 f"\ttype plain {d.name}"]
        if d.kind == "union":
            lines.append(f"\tswitch v.{go_field(d.discriminator)} {{")
        for required, tags in groups.items():
            if tags:
                lines.append("\tcase " + ", ".join(json.dumps(tag) for tag in tags) + ":")
            # Shadow only required or recursively wrapped fields. Embedding preserves optional/extraneous
            # fields and their legacy omitempty tags, and avoids marshaling any nested payload twice.
            selected = [f for f in fields if f.name in required or any(ref in wrapped for ref in refs(f.type))]
            lines += ["\t\treturn json.Marshal(struct {", "\t\t\tplain"]
            for f in selected:
                optional = d.kind == "union" or not f.required
                typ = wire_type(f.type, optional, f.pointer)
                tag = f.name + ("" if f.name in required else ",omitempty")
                lines.append(f'\t\t\t{go_field(f.name)} {typ} `json:"{tag}"`')
            lines += ["\t\t}{", "\t\t\tplain: plain(v),"]
            for f in selected:
                value = converted(f.type, "v." + go_field(f.name), d.kind == "union" or not f.required, f.pointer)
                lines.append(f"\t\t\t{go_field(f.name)}: {value},")
            lines.append("\t\t})")
        if d.kind == "union":
            lines += ["\tdefault:", "\t\treturn json.Marshal(plain(v))", "\t}"]
        return lines + ["}", ""]

    for d in defs.values():
        if d.union:
            continue
        if d.kind == "enum":
            out += comment("// ", named(d.name, d.doc) or f"Values of {d.name}.")
            out.append("const (")
            for v in d.values:
                out.append(f'\t{d.name}{camel(v)} = "{v}"')
            out += [")", "", f"// {plural(d.name)} are the values of {d.name}, in order.",
                    f"var {plural(d.name)} = []string{{{', '.join(json.dumps(v) for v in d.values)}}}", ""]
        elif d.kind == "any":
            out += comment("// ", d.doc) + [f"type {d.name} = json.RawMessage", ""]
        elif d.kind == "struct":
            out += comment("// ", named(d.name, d.doc))
            out.append(f"type {d.name} struct {{")
            for f in d.fields:
                out += field_line(f)
            if d.extra:
                out += ["\t// Extra keys stay at this object's level on the wire; they cannot replace declared fields.",
                        '\tAdditionalProperties map[string]json.RawMessage `json:"-"`']
            out += ["}", ""]
            if d.extra:
                keys = ", ".join(json.dumps(k) for k in reserved_keys(defs, d))
                out += [f"func (v *{d.name}) UnmarshalJSON(data []byte) error {{",
                        "\tvar extra map[string]json.RawMessage",
                        "\tif err := json.Unmarshal(data, &extra); err != nil { return err }",
                        "\tdeclared := map[string]json.RawMessage{}",
                        f"\tfor _, key := range []string{{{keys}}} {{",
                        "\t\tif value, ok := extra[key]; ok { declared[key] = value; delete(extra, key) }", "\t}",
                        "\tdata, err := json.Marshal(declared)", "\tif err != nil { return err }",
                        f"\ttype known {d.name}", "\tvar fields known",
                        "\tif err := json.Unmarshal(data, &fields); err != nil { return err }",
                        "\tfields.AdditionalProperties = extra", f"\t*v = {d.name}(fields)",
                        "\treturn nil", "}", "",
                        f"func (v {d.name}) MarshalJSON() ([]byte, error) {{",
                        f"\ttype known {d.name}", "\tdata, err := json.Marshal(known(v))",
                        "\tif err != nil { return nil, err }",
                        "\tvar fields map[string]json.RawMessage",
                        "\tif err := json.Unmarshal(data, &fields); err != nil { return nil, err }",
                        "\tfor key, value := range v.AdditionalProperties {"]
                if keys:
                    out += ["\t\tswitch key {", f"\t\tcase {keys}:", "\t\t\tcontinue", "\t\t}"]
                out += ["\t\tfields[key] = value", "\t}", "\treturn json.Marshal(fields)", "}", ""]
            elif d.preserve_required and any(ref in wrapped for f in d.fields for ref in refs(f.type)):
                out += marshaler(d, d.name)
        elif d.kind == "union":
            disc = d.discriminator
            out += comment("// ", named(d.name, d.doc) + f" One struct for every variant: {disc} says which fields "
                                  "mean something.")
            out.append(f"type {d.name} struct {{")
            out.append(f"\t{go_field(disc)} string `json:\"{disc}\"`")
            for f in flat_fields(defs, d):
                out += field_line(f, force_optional=True)
            out += ["}", "", f"// {d.name} {disc}s.", "const ("]
            for v in d.variants:
                out.append(f'\t{d.name}{camel(defs[v].tag)} = "{defs[v].tag}"')
            out += [")", "", f"// {d.name}{plural(go_field(disc))} are the {disc}s of {d.name}, in order.",
                    f"var {d.name}{plural(go_field(disc))} = []string{{"
                    + ", ".join(json.dumps(defs[v].tag) for v in d.variants) + "}", ""]
            if d.preserve_required:
                out += marshaler(d, d.name)
            if any(defs[v].since for v in d.variants):
                out += [f"// {d.name}Since is the UI version that brought each {disc}.",
                        f"var {d.name}Since = map[string]int{{"
                        + ", ".join(f"{json.dumps(defs[v].tag)}: {defs[v].since}" for v in d.variants) + "}", ""]
    for name in sorted(wrapped):
        out += [f"// requiredJSON{name} preserves required fields only inside stream payloads.",
                f"type requiredJSON{name} {name}", ""]
        out += marshaler(defs[name], "requiredJSON" + name)
    out += ["// newDef makes a value of each definition, for tests that read examples by definition name.",
            "var newDef = map[string]func() any{"]
    for d in defs.values():
        if d.kind in ("struct", "union") and not d.union:
            out.append(f"\t{json.dumps(d.name)}: func() any {{ return new({d.name}) }},")
    out += ["}", ""]
    out += go_calls(calls or [])
    return "\n".join(out)


