def gofmt(src: str) -> str:
    exe = shutil.which("gofmt")
    if not exe:
        raise SchemaError("gofmt is not on PATH: the Go output is gofmt's")
    r = subprocess.run([exe], input=src, capture_output=True, text=True)
    if r.returncode != 0:
        raise SchemaError("gofmt: " + r.stderr.strip())
    return r.stdout


def for_apps(defs: dict[str, Def]) -> dict[str, Def]:
    """The definitions the apps read: none of a plugin-side file's, which the apps' own may not refer to."""
    apps = {n: d for n, d in defs.items() if not d.side}

    def refs(t: TypeRef):
        while t is not None:
            if t.kind == "ref":
                yield t.ref
            t = t.of

    for d in apps.values():
        used = [r for t in [*(f.type for f in d.fields), *d.json_types] for r in refs(t)] + d.variants
        for r in used:
            if defs[r].side:
                raise SchemaError(f"{d.name} refers to {r}, which is {defs[r].side}-side: the apps do not have it")
    return apps


def outputs(defs: dict[str, Def]) -> dict[Path, str]:
    apps = for_apps(defs)
    # The calls are what a program and the hub say to each other: the SDKs' only.
    calls = load_calls(defs)
    ts, ts_apps = gen_ts(defs, calls), gen_ts(apps)
    # Apple stream reduction validates original JSON before projecting permissive legacy native models.
    # Keep validation constraints generated from the same schemas as the wire types.
    schema_docs = {f: json.loads((SCHEMA_DIR / f).read_text())
                   for f in ("stream.schema.json", "view.schema.json", "protocol.schema.json")}
    schema_json = json.dumps(schema_docs, ensure_ascii=True, separators=(",", ":"))
    swift_schemas = '\npublic nonisolated enum ExtensionWireSchemas {\n    public static let json = ###"' + schema_json + '"###\n}\n'
    out = {GO_OUT: gofmt(gen_go(defs, calls)), SWIFT_OUT: gen_swift(apps) + swift_schemas, KOTLIN_OUT: gen_kotlin(apps)}
    for p in TS_OUTS:
        out[p] = ts if p == TS_SDK_OUT else ts_apps
    for f in SCHEMA_FILES:
        out[GO_SCHEMA_DIR / f] = (SCHEMA_DIR / f).read_text()
    return {p: (s.rstrip("\n") + "\n") for p, s in out.items()}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on a difference")
    args = ap.parse_args()
    try:
        files = outputs(load())
    except SchemaError as e:
        print(f"schema/extension: {e}", file=sys.stderr)
        return 2
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    if not args.check:
        # sdk/ts/src/wire.ts is also in the bundle `personad extension new` writes extensions from.
        subprocess.run([sys.executable, str(ROOT / "scripts" / "gen" / "sdk_bundle.py")], check=True)
    if stale:
        print("generated files differ from schema/extension (run python3 scripts/gen/extension_schema.py):",
              file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
