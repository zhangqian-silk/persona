WEIGHTS = ["regular", "light", "bold", "fill", "duotone"]  # matches the PhIcon constructor order


def camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def paths(svg: str) -> list[str]:
    out = []
    for match in re.finditer(r"<path\b([^>]*)/?>", svg):
        attrs = match.group(1)
        d = re.search(r'\bd="([^"]+)"', attrs)
        if not d:
            continue
        faint = re.search(r'\bopacity="0?\.2"', attrs) is not None
        out.append(("~" if faint else "") + d.group(1))
    if re.search(r"<(rect|circle|line|polyline|polygon|ellipse)\b", svg):
        raise SystemExit("non-path element in an icon; extend the generator first")
    return out


def main() -> None:
    root, output, package = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    lines = [
        "// Generated by scripts/assets/gen_phosphor_icons.py from Phosphor Icons (MIT, https://phosphoricons.com); do not edit.",
        f"package {package}",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** One icon in every weight; each weight is built on first use. Paths starting with \"~\" are the 20% duotone layer. */",
        "class PhIcon internal constructor(",
        "    val name: String,",
        "    private val regularPaths: Array<String>,",
        "    private val lightPaths: Array<String>,",
        "    private val boldPaths: Array<String>,",
        "    private val fillPaths: Array<String>,",
        "    private val duotonePaths: Array<String>,",
        ") {",
        "    val regular: ImageVector by lazy { build(\"regular\", regularPaths) }",
        "    val light: ImageVector by lazy { build(\"light\", lightPaths) }",
        "    val bold: ImageVector by lazy { build(\"bold\", boldPaths) }",
        "    val fill: ImageVector by lazy { build(\"fill\", fillPaths) }",
        "    val duotone: ImageVector by lazy { build(\"duotone\", duotonePaths) }",
        "",
        "    private fun build(weight: String, paths: Array<String>): ImageVector =",
        "        ImageVector.Builder(\"$name-$weight\", 24.dp, 24.dp, 256f, 256f).apply {",
        "            for (path in paths) {",
        "                val faint = path.startsWith(\"~\")",
        "                addPath(addPathNodes(path.removePrefix(\"~\")), fill = SolidColor(Color.Black), fillAlpha = if (faint) 0.2f else 1f)",
        "            }",
        "        }.build()",
        "}",
        "",
        "object PhIcons {",
    ]
    for name in NAMES:
        args = []
        for weight in WEIGHTS:
            file = root / "assets" / weight / (f"{name}.svg" if weight == "regular" else f"{name}-{weight}.svg")
            data = paths(file.read_text())
            args.append("arrayOf(" + ", ".join(f'"{d}"' for d in data) + ")")
        lines.append(f'    val {camel(name)}: PhIcon by lazy {{ PhIcon("{name}", {", ".join(args)}) }}')
    lines.append("}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")
    print(f"{len(NAMES)} icons x {len(WEIGHTS)} weights -> {output}")


if __name__ == "__main__":
    main()
