#!/usr/bin/env python3
"""Generate Compose ImageVectors from a local Phosphor Icons checkout (MIT, https://phosphoricons.com).

    python3 -I scripts/assets/gen_phosphor_icons.py <phosphor-core checkout> <output.kt> <kotlin package>

Only the icons listed in NAMES are generated, in the weights listed in WEIGHTS. Every Phosphor SVG is a
256x256 view box made of filled <path> elements; duotone backgrounds carry opacity="0.2".
"""
