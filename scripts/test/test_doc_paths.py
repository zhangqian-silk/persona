QUOTED = re.compile(r"`([^`\s]+)`")

# A Markdown link target: [text](target) or [text](target "title"); <target> is unwrapped below.
# A bare target may hold one level of balanced parentheses, as in foo(1).md.
LINK = re.compile(r"\]\(\s*(<[^>]*>|(?:[^()\s]|\([^()\s]*\))+)(?:\s+\"[^\"]*\")?\s*\)")
# A fence line: three or more backticks or tildes, then the info string (CommonMark 4.5).
FENCE = re.compile(r"^[ \t]*(`{3,}|~{3,})(.*)$")
INLINE_CODE = re.compile(r"(`+).*?\1")
SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")

def current_docs():
    """Discover every maintained module guide, but not point-in-time archives."""
    return sorted(p for p in (ROOT / "docs").rglob("*.md")
                  if "archive" not in p.relative_to(ROOT / "docs").parts)


def doc_files():
    files = [ROOT / name for name in ("CLAUDE.md", "README.md", "README.zh-CN.md", "THIRD_PARTY_NOTICES.md", "scripts/README.md")]
    files += current_docs()
    files += module_docs()
    return [f for f in files if f.exists() and f.relative_to(ROOT).as_posix() not in SKIP_FILES]


def module_docs():
    # Tracked files only, so build output and node_modules under these directories are never scanned.
    listed = subprocess.run(["git", "ls-files", "-z", "--", *(f"{d}/*.md" for d in MODULE_DOC_DIRS)],
                            cwd=ROOT, check=True, capture_output=True, text=True).stdout
    return sorted(ROOT / name for name in listed.split("\0") if name)


def quoted_paths(line):
    for token in QUOTED.findall(line):
        # The spec READMEs name a symbol after a full-width colon: `apple/Shared/Models.swift` + the colon + `Interaction`.
        path = re.split(r"[:：]", token.split("#", 1)[0], maxsplit=1)[0].rstrip(".,;/")
        if "/" not in path or path.split("/", 1)[0] not in TOP + SERVER_RELATIVE:
            continue
        # Placeholders, globs, prefixes of a family of files and elided paths are not literal paths.
        if any(mark in path for mark in ("<", ">", "*", "{", "$", "…", "...")) or path.endswith(("-", "_")):
            continue
        yield path


def outside_fences(text):
    """Yield (line number, line) for each line outside fenced code blocks.

    A backtick fence's info string has no backtick, so a line that starts with an inline span showing a fence
    (```` ```mermaid ````) opens nothing. A fence closes at a line of its own character, at least as long, with
    nothing after it, or at the end of the file."""
    fence = ""
    for number, line in enumerate(text.splitlines(), 1):
        mark = FENCE.match(line)
        if not fence:
            if mark and not (mark[1][0] == "`" and "`" in mark[2]):
                fence = mark[1]
            else:
                yield number, line
        elif mark and mark[1][0] == fence[0] and len(mark[1]) >= len(fence) and not mark[2].strip():
            fence = ""


def link_targets(text):
    """Yield (line number, path) for each relative link target outside code blocks and inline code."""
    for number, line in outside_fences(text):
        for target in LINK.findall(INLINE_CODE.sub("", line)):
            target = target.strip("<>")
            if not target or target.startswith("#") or SCHEME.match(target):  # anchors, URLs, mailto:
                continue
            path = unquote(target.split("#", 1)[0].split("?", 1)[0])
            if path:
                yield number, path


def missing_links(doc):
    """Return doc:line: target for every relative link whose file is not on disk."""
    found = []
    for number, path in link_targets(doc.read_text(errors="ignore")):
        resolved = ROOT / path.lstrip("/") if path.startswith("/") else doc.parent / path
        if not resolved.exists():
            found.append(f"{doc.relative_to(ROOT)}:{number}: {path}")
    return found


def generated_screenshot(path):
    producer = GENERATED_SCREENSHOTS.get(path)
    if producer is None:
        return False
    source = ROOT / producer
    if not source.is_file():
        return False
    output = "build/" + path.split("/build/", 1)[1]
    pattern = (r'(?m)^\s*private\s+fun\s+out\(\)(?:\s*:\s*File)?\s*=\s*'
               r'File\(\s*System\.getProperty\("persona\.shots"\)\s*\?:\s*"'
               + re.escape(output) + r'"\s*\)')
    return re.search(pattern, source.read_text()) is not None


def exists(path):
    if path in GENERATED_SCREENSHOTS:
        return generated_screenshot(path)
    if path in GENERATED or path in ELSEWHERE:
        return True
    if path.split("/", 1)[0] in SERVER_RELATIVE:
        return (ROOT / "server" / path).exists()
    return (ROOT / path).exists() or (ROOT / "scripts" / path).exists()


class DocPathTests(unittest.TestCase):
    def test_generated_screenshots_have_matching_source_producers(self):
        for path in GENERATED_SCREENSHOTS:
            with self.subTest(path=path):
                self.assertTrue(generated_screenshot(path))
                self.assertTrue(exists(path))

    def test_missing_or_changed_producers_and_unknown_outputs_are_rejected(self):
        path, producer = next(iter(GENERATED_SCREENSHOTS.items()))
        output = "build/" + path.split("/build/", 1)[1]
        with tempfile.TemporaryDirectory(prefix="doc-shot-producer-") as directory:
            root = Path(directory)
            with patch(__name__ + ".ROOT", root):
                (root / path).mkdir(parents=True)
                self.assertFalse(exists(path))
                source = root / producer
                source.parent.mkdir(parents=True)
                source.write_text(f'// private fun out() = File(System.getProperty("persona.shots") ?: "{output}")\n'
                                  'private fun out() = File(System.getProperty("persona.shots") ?: "build/other-shots")\n')
                self.assertFalse(exists(path))
                source.write_text(f'private fun out() = File(System.getProperty("persona.shots") ?: "{output}")\n')
                self.assertTrue(exists(path))
                source.unlink()
                self.assertFalse(exists(path))
                self.assertFalse(exists(path + "-unknown"))
                self.assertFalse(exists("android/feature/missing/src/Unknown.kt"))

    def test_symbol_after_a_colon_is_not_part_of_the_path(self):
        self.assertEqual(["apple/Shared/Models.swift"], list(quoted_paths("`apple/Shared/Models.swift：Interaction`")))
        self.assertEqual(["server/internal/hub/hub.go"], list(quoted_paths("`server/internal/hub/hub.go:120`")))

    def test_module_docs_are_checked(self):
        checked = {doc.relative_to(ROOT).as_posix() for doc in doc_files()}
        for doc in ("README.md", "README.zh-CN.md", "spec/README.md", "spec/fixtures/wire/README.md", "spec/tokens/README.md", "sdk/README.md",
                    "sdk/templates/go/README.md", "schema/extension/README.md", "integrations/pi/README.md",
                    "android/feature/chat/INTEGRATION.md"):
            self.assertIn(doc, checked)
        self.assertEqual(len(checked), len(doc_files()), "a doc is listed twice")

    def test_sdk_and_schema_paths_are_checked(self):
        paths = list(quoted_paths("`sdk/go/sdk.go` and `schema/extension/view.schema.json：Card`"))
        self.assertEqual(["sdk/go/sdk.go", "schema/extension/view.schema.json"], paths)
        self.assertTrue(all(exists(path) for path in paths))
        self.assertFalse(exists("sdk/go/missing.go"))

    def test_server_relative_go_paths_resolve_under_server(self):
        self.assertEqual(["internal/hub/hub.go"], list(quoted_paths("see `internal/hub/hub.go` and `internal` and `go`")))
        with tempfile.TemporaryDirectory(prefix="doc-server-paths-") as directory:
            root = Path(directory)
            with patch(__name__ + ".ROOT", root):
                (root / "server/internal/devices").mkdir(parents=True)
                (root / "server/internal/devices/tailcat_e2e_test.go").write_text("package devices\n")
                (root / "internal/hub").mkdir(parents=True)
                (root / "internal/hub/tailcat_e2e_test.go").write_text("package hub\n")
                self.assertTrue(exists("internal/devices/tailcat_e2e_test.go"))
                # Only server/ counts: a file at the repository root or a moved file does not satisfy the doc.
                self.assertFalse(exists("internal/hub/tailcat_e2e_test.go"))
                self.assertFalse(exists("internal/node/missing_test.go"))

    def test_quoted_repository_paths_exist(self):
        missing = []
        for doc in doc_files():
            for number, line in enumerate(doc.read_text(errors="ignore").splitlines(), 1):
                if "github.com/" in line:  # a path inside another project, quoted with its source
                    continue
                missing += [f"{doc.relative_to(ROOT)}:{number}: {path}" for path in quoted_paths(line) if not exists(path)]
        self.assertEqual([], missing, "docs quote paths that are not in the repository; update them to where the file is now")

    def test_markdown_link_targets_exist(self):
        missing = [entry for doc in doc_files() for entry in missing_links(doc)]
        self.assertEqual([], missing, "docs link to files that are not in the repository; update the link targets")

    def test_missing_link_targets_are_reported(self):
        with tempfile.TemporaryDirectory(prefix="doc-links-") as directory:
            root = Path(directory)
            with patch(__name__ + ".ROOT", root):
                (root / "spec/fixtures/wire").mkdir(parents=True)
                (root / "spec/fixtures/wire/inbox.json").write_text("{}\n")
                (root / "docs/protocol").mkdir(parents=True)
                (root / "docs/protocol/protocol.md").write_text("# protocol\n")
                (root / "spec/fixtures/wire/foo(1).md").write_text("# foo\n")
                doc = root / "spec/fixtures/wire/README.md"
                doc.write_text("\n".join([
                    "| [inbox.json](inbox.json) | [lark.json](lark.json) |",
                    "[协议](../../../docs/protocol/protocol.md#hello) [root](/docs/protocol/protocol.md) [gone](../../../docs/gone.md \"t\")",
                    "[web](https://example.com/x.md) [mail](mailto:me@example.com) [top](#规则与用例)",
                    "`[code](inline-missing.md)` and <a href=x>",
                    "[paren](foo(1).md) [paren gone](bar(2).md)",
                    "```md",
                    "[fenced](fenced-missing.md)",
                    "```",
                    "  ```` ```mermaid ```` starts a line but is an inline span, not a fence",
                    "[after the span](span-missing.md)",
                    "````md",
                    "```",
                    "[inside the longer fence](long-missing.md)",
                    "````",
                    "[after the long fence](long-after-missing.md)",
                ]) + "\n")
                self.assertEqual(["spec/fixtures/wire/README.md:1: lark.json",
                                  "spec/fixtures/wire/README.md:2: ../../../docs/gone.md",
                                  "spec/fixtures/wire/README.md:5: bar(2).md",
                                  "spec/fixtures/wire/README.md:10: span-missing.md",
                                  "spec/fixtures/wire/README.md:15: long-after-missing.md"], missing_links(doc))

    def test_module_guides_are_discovered_recursively(self):
        with tempfile.TemporaryDirectory(prefix="doc-modules-") as directory:
            root = Path(directory)
            for name in ("docs/README.md", "docs/apple/ios.md", "docs/server/hub/update.md",
                         "docs/lessons/testing.md", "docs/archive/apple/old.md"):
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text("# Guide\n")
            with patch(__name__ + ".ROOT", root):
                self.assertEqual(["docs/README.md", "docs/apple/ios.md", "docs/lessons/testing.md",
                                  "docs/server/hub/update.md"],
                                 [p.relative_to(root).as_posix() for p in current_docs()])

    def test_current_docs_are_in_the_index(self):
        index = (ROOT / "CLAUDE.md").read_text().split("\n## Docs index\n", 1)[1]
        rows = "\n".join(line for line in index.splitlines() if line.startswith("|"))
        docs = [doc.relative_to(ROOT).as_posix() for doc in current_docs()
                if "lessons" not in doc.relative_to(ROOT / "docs").parts]
        missing = [doc for doc in docs if f"`{doc}`" not in rows]
        self.assertEqual([], missing, "add these docs to the Docs index in CLAUDE.md")

    def test_archive_records_are_in_the_archive_table(self):
        archive = ROOT / "docs/archive"
        rows = "\n".join(line for line in (archive / "README.md").read_text().splitlines() if line.startswith("|"))
        records = sorted(p.relative_to(archive).as_posix() for p in archive.rglob("*.md") if p.name != "README.md")
        missing = [record for record in records if f"`{record}`" not in rows]
        self.assertEqual([], missing, "add these records to the table in docs/archive/README.md")


if __name__ == "__main__":
    unittest.main()
