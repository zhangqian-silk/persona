// AnswerComputerElicit is the node's computer.elicit: LCU asked something while a computer call was running. The
// card is a permission or a question, the same ones the phone and the web already show for app approval and
// "ask before acting". The answer is the MCP elicitation result. The model cannot approve it: a resolution the
// assistant wrote, or anything that is not an allow on that card, comes back as cancel.
func (h *Manager) AnswerComputerElicit(ctx context.Context, machineID string, params json.RawMessage) (map[string]any, error) {
	m := h.machineByID(machineID)
	if m == nil {
		return map[string]any{"action": "cancel"}, nil
	}
	return h.answerComputerElicit(ctx, m, params)
}

func (h *Manager) answerComputerElicit(ctx context.Context, m *Machine, params json.RawMessage) (map[string]any, error) {
	var p struct {
		Conversation string          `json:"conversation"`
		Params       json.RawMessage `json:"params"`
	}
	if err := json.Unmarshal(params, &p); err != nil {
		return map[string]any{"action": "cancel"}, nil
	}
	if name, id, ok := lcuconfirm.NativeApp(p.Params); ok && protectedApp(approvedApp{BundleID: id, Name: name}) {
		// Never System Settings or a permission prompt (#4336): refused, with no card to allow it on.
		h.logf("[%s] computer elicitation refused: protected app %s", m.cfg.ID, cmp.Or(id, name))
		return lcuconfirm.Decline(), nil
	}
	l := h.userLang()
	original := lcuconfirm.Card(p.Params)
	ix, choices := computerElicitPresentation(l, p.Params, original)
	ix.ID = "ix_" + randomHex(6)
	ix.MachineID = m.cfg.ID
	ix.SessionTitle = "Persona"
	ix.CreatedAt = time.Now().UTC()
	ix.ExpiresAt = time.Now().Add(15 * time.Minute).UTC()
	if home := h.sessionHome(p.Conversation); home != "" {
		// On the assistant conversation the card is enabled, and the assistant's own answer tool refuses it.
		ix.MachineID, ix.SessionID = home, p.Conversation
	}
	if ix.Summary != "" {
		ix.Summary = i18n.T(l, "hub-computer.lcu_machine", i18n.Args{"machine": m.name(), "summary": ix.Summary})
	}
	if ix.Kind == proto.IxQuestion && len(ix.Questions) > 0 {
		ix.Questions[0].Question = ix.Summary
	}
	if lcuconfirm.Kind(p.Params) == lcuconfirm.KindNative {
		// Both persistence scopes need a four-option question presentation, but this is still a permission wait.
		ctx = mcpwait.WithInteractionKind(ctx, ix.ID, proto.MCPWaitApproval)
	}
	res, _ := h.waitInteraction(ctx, ix)
	// Restore only labels generated by the bridge. Runtime enum values and form fields remain original.
	if len(res.Answers) > 0 {
		answers := make(map[string]string, len(res.Answers))
		for question, answer := range res.Answers {
			if canonical, ok := choices[answer]; ok {
				answer = canonical
			}
			answers[question] = answer
		}
		res.Answers = answers
	}
	out := lcuconfirm.Answer(p.Params, res)
	action, _ := out["action"].(string)
	h.logf("[%s] computer elicitation %s → %s", m.cfg.ID, lcuconfirm.Kind(p.Params), action)
	return out, nil
}

// computerElicitPresentation localizes only text generated by lcuconfirm, not the runtime's message, warning,
// enum values or field labels. The original card and parser remain canonical for older clients and MCP replies.
func computerElicitPresentation(l i18n.Lang, raw json.RawMessage, original proto.Interaction) (proto.Interaction, map[string]string) {
	ix := original
	kind := lcuconfirm.Kind(raw)
	choices := map[string]string{}
	text := func(key string) string { return i18n.T(l, "hub-computer."+key) }
	source := func(key string) string { return i18n.T(i18n.Default, "hub-computer."+key) }
	ix.ToolName = text("lcu_tool")
	ix.Questions = append([]proto.Question(nil), original.Questions...)
	for q := range ix.Questions {
		ix.Questions[q].Header = text("lcu_tool")
		ix.Questions[q].Options = append([]proto.QuestionOption(nil), original.Questions[q].Options...)
		for n := range ix.Questions[q].Options {
			option := &ix.Questions[q].Options[n]
			var key string
			if kind == lcuconfirm.KindNative {
				key = []string{"lcu_once", "lcu_session", "lcu_always", "lcu_deny"}[n]
			} else if kind == lcuconfirm.KindEnum && n == len(ix.Questions[q].Options)-1 {
				key = "lcu_deny"
			}
			if key == "" {
				continue // an original runtime option
			}
			label := text(key)
			// An original enum may equal the translated decline label. Never reinterpret that original value.
			if kind == lcuconfirm.KindEnum {
				for {
					collision := false
					for _, other := range original.Questions[q].Options[:n] {
						collision = collision || other.Label == label
					}
					if !collision {
						break
					}
					label = i18n.T(l, "hub-computer.lcu_cancel_label", i18n.Args{"label": label})
				}
			}
			choices[label] = option.Label
			option.Label = label
			if option.Description != "" {
				option.Description = text(key + "_detail")
			}
		}
	}
	if ix.AlwaysLabel != "" && kind == lcuconfirm.KindNative {
		for _, key := range []string{"lcu_always", "lcu_session"} {
			if app, ok := strings.CutPrefix(ix.AlwaysLabel, source(key)); ok {
				// i18n-ignore: strip the parser's canonical app quotation, never translate the app name.
				app = strings.TrimSuffix(strings.TrimPrefix(app, "「"), "」")
				if app == "" {
					ix.AlwaysLabel = text(key)
				} else {
					ix.AlwaysLabel = i18n.T(l, "hub-computer."+key+"_app", i18n.Args{"app": app})
				}
				break
			}
		}
	}
	var params struct {
		Meta struct {
			Risk string `json:"riskLevel"`
		} `json:"_meta"`
	}
	_ = json.Unmarshal(raw, &params)
	summary := ix.Summary
	high := params.Meta.Risk == "high"
	if high {
		summary = strings.TrimPrefix(summary, source("lcu_high_risk")+"\n")
	}
	if kind == lcuconfirm.KindNative || kind == lcuconfirm.KindOrigin {
		line, rest, ok := strings.Cut(summary, "\n")
		if ok {
			if kind == lcuconfirm.KindNative {
				if app, found := strings.CutPrefix(line, "允许操控「"); found { // i18n-ignore: canonical parser-generated prefix
					app = strings.TrimSuffix(app, "」？")
					line = i18n.T(l, "hub-computer.lcu_app", i18n.Args{"app": app})
				}
			} else if origin, found := strings.CutPrefix(line, "允许浏览器访问 "); found { // i18n-ignore: canonical parser-generated prefix
				line = i18n.T(l, "hub-computer.lcu_origin", i18n.Args{"origin": strings.TrimSuffix(origin, "？")})
			}
			summary = strings.TrimSpace(line + "\n" + rest)
		} else if kind == lcuconfirm.KindNative {
			if app, found := strings.CutPrefix(summary, "允许操控「"); found { // i18n-ignore: canonical parser-generated prefix
				summary = i18n.T(l, "hub-computer.lcu_app", i18n.Args{"app": strings.TrimSuffix(app, "」？")})
			}
		} else if origin, found := strings.CutPrefix(summary, "允许浏览器访问 "); found { // i18n-ignore: canonical parser-generated prefix
			summary = i18n.T(l, "hub-computer.lcu_origin", i18n.Args{"origin": strings.TrimSuffix(origin, "？")})
		}
	}
	if kind == lcuconfirm.KindOther {
		summary = strings.TrimSuffix(summary, "\n"+source("lcu_cancel"))
		if summary == source("lcu_other") {
			summary = text("lcu_other")
		}
		summary += "\n" + text("lcu_cancel")
	}
	if summary == source("lcu_ask") {
		summary = text("lcu_ask")
	}
	if high {
		summary = text("lcu_high_risk") + "\n" + summary
	}
	ix.Summary = summary
	return ix, choices
}

// sessionHome is the machine that lists this conversation, so a card for it shows in that chat.
func (h *Manager) sessionHome(id string) string {
	if id == "" {
		return ""
	}
	for _, m := range h.machinesNow() {
		if h.findSession(m, func(s *proto.Session) bool { return s.SessionID == id }) {
			return m.cfg.ID
		}
	}
	return ""
}
