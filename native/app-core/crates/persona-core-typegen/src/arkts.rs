//! The ArkTS codec follows the Rust registry directly: every integer is written and read at its own width
//! (`native/app-core/README.md`, the ArkTS host replay checks the bytes against Rust). Serde-generate has no
//! ArkTS backend; emitting strict, explicit
//! unions avoids loose TypeScript objects, dynamic property access and a second hand-maintained wire schema.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io;
use std::path::Path;

use serde_reflection::{ContainerFormat, Format, Named, VariantFormat};

pub fn write(root: &Path, registry: &BTreeMap<String, ContainerFormat>) -> io::Result<()> {
    let mut source = String::from(
        "/* Generated by persona-core-typegen. Do not edit. Bincode uses fixed-width little-endian integers. */\n\
         class Writer {\n\
           [key: string]: (key: string) => Object | number[];\n\
           private bytes: number[] = [];\n\
           register(name: string, write: (key: string) => Object): void { this[name] = write; }\n\
           private integer(value: number): void { if (!Number.isSafeInteger(value)) throw new Error('wire integer out of range'); }\n\
           u8(value: number): void { this.integer(value); if (value < 0 || value > 255) throw new Error('u8 out of range'); this.bytes.push(value); }\n\
           u16(value: number): void { this.integer(value); if (value < 0 || value > 65535) throw new Error('u16 out of range'); this.bytes.push(value & 255, (value >>> 8) & 255); }\n\
           u32(value: number): void { this.integer(value); if (value < 0 || value > 4294967295) throw new Error('u32 out of range'); this.bytes.push(value & 255, (value >>> 8) & 255, (value >>> 16) & 255, (value >>> 24) & 255); }\n\
           u64(value: number): void { this.integer(value); if (value < 0) throw new Error('u64 out of range'); const low = value % 4294967296; this.u32(low < 0 ? low + 4294967296 : low); const high = Math.floor(value / 4294967296); this.u32(high < 0 ? high + 4294967296 : high); }\n\
           i8(value: number): void { this.integer(value); if (value < -128 || value > 127) throw new Error('i8 out of range'); this.u8(value < 0 ? value + 256 : value); }\n\
           i16(value: number): void { this.integer(value); if (value < -32768 || value > 32767) throw new Error('i16 out of range'); this.u16(value < 0 ? value + 65536 : value); }\n\
           i32(value: number): void { this.integer(value); if (value < -2147483648 || value > 2147483647) throw new Error('i32 out of range'); this.u32(value < 0 ? value + 4294967296 : value); }\n\
           i64(value: number): void { this.integer(value); const low = value % 4294967296; this.u32(low < 0 ? low + 4294967296 : low); const high = Math.floor(value / 4294967296); this.u32(high < 0 ? high + 4294967296 : high); }\n\
           bool(value: boolean): void { this.u8(value ? 1 : 0); }\n\
           string(value: string): void { const bytes = new TextEncoder().encode(value); this.u64(bytes.length); for (const byte of bytes) this.bytes.push(byte); }\n\
           option<T>(value: T | null, write: (value: T) => void): void { if (value === null) { this.u8(0); } else { this.u8(1); write(value); } }\n\
           seq<T>(values: T[], write: (value: T) => void): void { this.u64(values.length); for (const value of values) write(value); }\n\
           finish(): Uint8Array { return Uint8Array.from(this.bytes); }\n\
         }\n\n\
         class Reader {\n\
           [key: string]: (key: string) => Object | Uint8Array | number;\n\
           private offset = 0;\n\
           private readonly bytes: Uint8Array;\n\
           constructor(bytes: Uint8Array) { this.bytes = bytes; }\n\
           register(name: string, read: (key: string) => Object): void { this[name] = read; }\n\
           u8(): number { if (this.offset >= this.bytes.length) throw new Error('truncated wire input'); return this.bytes[this.offset++]; }\n\
           u16(): number { return this.u8() + this.u8() * 256; }\n\
           u32(): number { return this.u8() + this.u8() * 256 + this.u8() * 65536 + this.u8() * 16777216; }\n\
           i8(): number { const value = this.u8(); return value < 128 ? value : value - 256; }\n\
           i16(): number { const value = this.u16(); return value < 32768 ? value : value - 65536; }\n\
           i32(): number { const value = this.u32(); return value < 2147483648 ? value : value - 4294967296; }\n\
           u64(): number { const value = this.u32() + this.u32() * 4294967296; if (!Number.isSafeInteger(value)) throw new Error('u64 out of range'); return value; }\n\
           i64(): number { const low = this.u32(); let high = this.u32(); if (high >= 2147483648) high -= 4294967296; const value = high * 4294967296 + low; if (!Number.isSafeInteger(value)) throw new Error('i64 out of range'); return value; }\n\
           bool(): boolean { const value = this.u8(); if (value > 1) throw new Error('invalid boolean'); return value === 1; }\n\
           string(): string { const length = this.u64(); if (length > this.bytes.length - this.offset) throw new Error('truncated string'); const bytes = this.bytes.subarray(this.offset, this.offset + length); this.offset += length; return new TextDecoder().decode(bytes); }\n\
           option<T>(read: () => T): T | null { return this.bool() ? read() : null; }\n\
           seq<T>(read: () => T): T[] { const length = this.u64(); if (length > this.bytes.length - this.offset) throw new Error('invalid sequence length'); const result: T[] = []; for (let i = 0; i < length; i++) result.push(read()); return result; }\n\
           finish(): void { if (this.offset !== this.bytes.length) throw new Error('trailing wire input'); }\n\
         }\n\n",
    );
    for name in registry.keys() {
        write_type(&mut source, name, &registry[name]);
    }
    for (name, format) in registry {
        register_codecs(&mut source, name);
        write_codec(&mut source, name, format);
    }
    let registrations = registry
        .keys()
        .map(|name| format!("  register{name}(writer, reader);\n"))
        .collect::<String>();
    source.push_str("function register(writer: Writer, reader: Reader): void {\n");
    source.push_str(&registrations);
    source.push_str("}\n");
    for name in registry.keys() {
        writeln!(
            source,
            "export function encode{name}(value: {name}): Uint8Array {{ const writer = new Writer(); register(writer, new Reader(new Uint8Array())); writer.{method}(value); return writer.finish(); }}",
            method = function(name)
        )
        .unwrap();
        writeln!(
            source,
            "export function decode{name}(bytes: Uint8Array): {name} {{ const reader = new Reader(bytes); register(new Writer(), reader); const value = reader.{method}(); reader.finish(); return value; }}",
            method = function(name)
        )
        .unwrap();
    }
    std::fs::create_dir_all(root)?;
    std::fs::write(root.join("Wire.ts"), source)
}

fn function(name: &str) -> String {
    let mut result = String::new();
    let mut upper = false;
    for character in name.chars() {
        if character == '_' {
            upper = true;
        } else if upper || result.is_empty() {
            result.extend(character.to_uppercase());
            upper = false;
        } else {
            result.push(character);
        }
    }
    result
}

fn snake(name: &str) -> String {
    let mut result = String::new();
    for (index, character) in name.chars().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            result.push('_');
        }
        result.extend(character.to_lowercase());
    }
    result
}

fn type_name(format: &Format) -> String {
    match format {
        Format::Unit => "null".into(),
        Format::Bool => "boolean".into(),
        Format::I8 | Format::I16 | Format::I32 | Format::I64 | Format::U8 | Format::U16 | Format::U32 | Format::U64 => {
            "number".into()
        }
        Format::Str => "string".into(),
        Format::Bytes => "Uint8Array".into(),
        Format::TypeName(name) => name.clone(),
        Format::Option(format) => format!("{} | null", type_name(format)),
        Format::Seq(format) => format!("{}[]", type_name(format)),
        other => panic!("unsupported ArkTS wire type: {other:?}"),
    }
}

fn write_type(source: &mut String, name: &str, format: &ContainerFormat) {
    match format {
        ContainerFormat::UnitStruct => {
            writeln!(source, "export class {name} {{\n  private constructor() {{}}\n  static readonly shared: {name} = new {name}();\n}}\n").unwrap();
        }
        ContainerFormat::Struct(fields) => {
            writeln!(source, "export interface {name} {{").unwrap();
            for field in fields {
                writeln!(source, "  readonly {}: {};", field.name, type_name(&field.value)).unwrap();
            }
            writeln!(source, "}}\n").unwrap();
        }
        ContainerFormat::Enum(variants) => {
            write!(source, "export type {name} =").unwrap();
            for variant in variants.values() {
                write!(source, "\n  | {{ readonly kind: \"{}\"", snake(&variant.name)).unwrap();
                write_variant_type(source, &variant.value);
                write!(source, " }}").unwrap();
            }
            writeln!(source, ";\n").unwrap();
        }
        other => panic!("unsupported ArkTS container {name}: {other:?}"),
    }
}

fn write_variant_type(source: &mut String, variant: &VariantFormat) {
    match variant {
        VariantFormat::Unit => {}
        VariantFormat::NewType(format) => write!(source, "; readonly value: {}", type_name(format)).unwrap(),
        VariantFormat::Tuple(formats) => {
            for (index, format) in formats.iter().enumerate() {
                write!(source, "; readonly value{index}: {}", type_name(format)).unwrap();
            }
        }
        VariantFormat::Struct(fields) => {
            for field in fields {
                write!(source, "; readonly {}: {}", field.name, type_name(&field.value)).unwrap();
            }
        }
        VariantFormat::Variable(_) => panic!("unresolved wire variant"),
    }
}

fn register_codecs(source: &mut String, name: &str) {
    writeln!(
        source,
        "function register{name}(writer: Writer, reader: Reader): void {{"
    )
    .unwrap();
    writeln!(
        source,
        "  writer.register('{name}', (value: {name}) => write{name}(writer, value));"
    )
    .unwrap();
    writeln!(source, "  reader.register('{name}', () => read{name}(reader));").unwrap();
    writeln!(source, "}}").unwrap();
}

fn write_codec(source: &mut String, name: &str, format: &ContainerFormat) {
    match format {
        ContainerFormat::UnitStruct => {
            writeln!(
                source,
                "function write{name}(writer: Writer, _value: {name}): void {{}}\n"
            )
            .unwrap();
            writeln!(
                source,
                "function read{name}(reader: Reader): {name} {{ return {name}.shared; }}\n"
            )
            .unwrap();
        }
        ContainerFormat::Struct(fields) => {
            writeln!(source, "function write{name}(writer: Writer, value: {name}): void {{").unwrap();
            for field in fields {
                writeln!(
                    source,
                    "  {};",
                    write_format(&field.value, &format!("value.{}", field.name))
                )
                .unwrap();
            }
            writeln!(source, "}}\n").unwrap();
            if fields.is_empty() {
                writeln!(
                    source,
                    "function read{name}(reader: Reader): {name} {{ return {{}}; }}\n"
                )
                .unwrap();
            } else {
                writeln!(source, "function read{name}(reader: Reader): {name} {{\n  return {{").unwrap();
                for field in fields {
                    writeln!(source, "    {}: {},", field.name, read_format(&field.value)).unwrap();
                }
                writeln!(source, "  }};\n}}\n").unwrap();
            }
        }
        ContainerFormat::Enum(variants) => {
            writeln!(
                source,
                "function write{name}(writer: Writer, value: {name}): void {{\n  switch (value.kind) {{"
            )
            .unwrap();
            for (index, variant) in variants {
                writeln!(source, "    case \"{}\":", snake(&variant.name)).unwrap();
                writeln!(source, "      writer.u32({index});").unwrap();
                write_variant(source, &variant.value, "value");
                writeln!(source, "      break;").unwrap();
            }
            writeln!(source, "  }}\n}}\n").unwrap();
            writeln!(
                source,
                "function read{name}(reader: Reader): {name} {{\n  const variant = reader.u32();\n  switch (variant) {{"
            )
            .unwrap();
            for (index, variant) in variants {
                write!(source, "    case {index}: return {{ kind: \"{}\"", snake(&variant.name)).unwrap();
                read_variant(source, &variant.value);
                writeln!(source, " }};").unwrap();
            }
            writeln!(
                source,
                "    default: throw new Error('unknown {name} variant: ' + variant);\n  }}\n}}\n"
            )
            .unwrap();
        }
        other => panic!("unsupported ArkTS codec {name}: {other:?}"),
    }
}

fn write_format(format: &Format, value: &str) -> String {
    match format {
        Format::Unit => String::new(),
        Format::Bool => format!("writer.bool({value});"),
        Format::I8 => format!("writer.i8({value});"),
        Format::I16 => format!("writer.i16({value});"),
        Format::I32 => format!("writer.i32({value});"),
        Format::I64 => format!("writer.i64({value});"),
        Format::U8 => format!("writer.u8({value});"),
        Format::U16 => format!("writer.u16({value});"),
        Format::U32 => format!("writer.u32({value});"),
        Format::U64 => format!("writer.u64({value});"),
        Format::Str => format!("writer.string({value});"),
        Format::Bytes => format!("writer.u64({value}.length); for (const byte of {value}) writer.u8(byte);"),
        Format::TypeName(name) => format!("writer.{function}({value});", function = function(name)),
        Format::Option(format) => format!(
            "writer.option({value}, (item: {}) => {{ {} }});",
            type_name(format),
            write_format(format, "item")
        ),
        Format::Seq(format) => format!(
            "writer.seq({value}, (item: {}) => {{ {} }});",
            type_name(format),
            write_format(format, "item")
        ),
        other => panic!("unsupported ArkTS field: {other:?}"),
    }
}

fn write_variant(source: &mut String, variant: &VariantFormat, value: &str) {
    match variant {
        VariantFormat::Unit => {}
        VariantFormat::NewType(format) => {
            writeln!(source, "      {};", write_format(format, &format!("{value}.value"))).unwrap()
        }
        VariantFormat::Tuple(formats) => {
            for (index, format) in formats.iter().enumerate() {
                writeln!(
                    source,
                    "      {};",
                    write_format(format, &format!("{value}.value{index}"))
                )
                .unwrap();
            }
        }
        VariantFormat::Struct(fields) => {
            for Named { name, value: format } in fields {
                writeln!(source, "      {};", write_format(format, &format!("{value}.{name}"))).unwrap();
            }
        }
        VariantFormat::Variable(_) => panic!("unresolved wire variant"),
    }
}

fn read_format(format: &Format) -> String {
    match format {
        Format::Unit => "null".into(),
        Format::Bool => "reader.bool()".into(),
        Format::I8 => "reader.i8()".into(),
        Format::I16 => "reader.i16()".into(),
        Format::I32 => "reader.i32()".into(),
        Format::I64 => "reader.i64()".into(),
        Format::U8 => "reader.u8()".into(),
        Format::U16 => "reader.u16()".into(),
        Format::U32 => "reader.u32()".into(),
        Format::U64 => "reader.u64()".into(),
        Format::Str => "reader.string()".into(),
        Format::Bytes => "Uint8Array.from(reader.seq(() => reader.u8()))".into(),
        Format::TypeName(name) => format!("reader.{function}()", function = function(name)),
        Format::Option(format) => format!("reader.option(() => {})", read_format(format)),
        Format::Seq(format) => format!("reader.seq(() => {})", read_format(format)),
        other => panic!("unsupported ArkTS field: {other:?}"),
    }
}

fn read_variant(source: &mut String, variant: &VariantFormat) {
    match variant {
        VariantFormat::Unit => {}
        VariantFormat::NewType(format) => write!(source, ", value: {}", read_format(format)).unwrap(),
        VariantFormat::Tuple(formats) => {
            for (index, format) in formats.iter().enumerate() {
                write!(source, ", value{index}: {}", read_format(format)).unwrap();
            }
        }
        VariantFormat::Struct(fields) => {
            for Named { name, value: format } in fields {
                write!(source, ", {name}: {}", read_format(format)).unwrap();
            }
        }
        VariantFormat::Variable(_) => panic!("unresolved wire variant"),
    }
}
